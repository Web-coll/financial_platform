import { decimal, int, json, mysqlEnum, mysqlTable, text, timestamp, varchar } from "drizzle-orm/mysql-core";
import { relations } from "drizzle-orm";

/**
 * Core user table backing auth flow.
 * Extend this file with additional tables as your product grows.
 * Columns use camelCase to match both database fields and generated types.
 */
export const users = mysqlTable("users", {
  /**
   * Surrogate primary key. Auto-incremented numeric value managed by the database.
   * Use this for relations between tables.
   */
  id: int("id").autoincrement().primaryKey(),
  /** Manus OAuth identifier (openId) returned from the OAuth callback. Unique per user. */
  openId: varchar("openId", { length: 64 }).notNull().unique(),
  name: text("name"),
  email: varchar("email", { length: 320 }),
  loginMethod: varchar("loginMethod", { length: 64 }),
  role: mysqlEnum("role", ["user", "admin"]).default("user").notNull(),
  createdAt: timestamp("createdAt").defaultNow().notNull(),
  updatedAt: timestamp("updatedAt").defaultNow().onUpdateNow().notNull(),
  lastSignedIn: timestamp("lastSignedIn").defaultNow().notNull(),
});

export type User = typeof users.$inferSelect;
export type InsertUser = typeof users.$inferInsert;

/**
 * Financial profile for each user.
 * Stores core financial information collected during onboarding.
 */
export const financialProfiles = mysqlTable("financial_profiles", {
  id: int("id").autoincrement().primaryKey(),
  userId: int("userId").notNull(),
  monthlyIncome: decimal("monthlyIncome", { precision: 12, scale: 2 }).notNull(),
  incomeType: mysqlEnum("incomeType", ["fixed", "variable"]).notNull(),
  hasFixedExpenses: int("hasFixedExpenses").notNull(), // 0 or 1 (boolean)
  fixedExpensesAmount: decimal("fixedExpensesAmount", { precision: 12, scale: 2 }),
  hasDebts: int("hasDebts").notNull(), // 0 or 1 (boolean)
  totalDebts: decimal("totalDebts", { precision: 12, scale: 2 }),
  currentSavings: decimal("currentSavings", { precision: 12, scale: 2 }),
  riskProfile: mysqlEnum("riskProfile", ["conservative", "moderate", "aggressive"]).default("moderate"),
  investmentExperience: mysqlEnum("investmentExperience", ["beginner", "intermediate", "advanced"]).default("beginner"),
  completedOnboarding: int("completedOnboarding").default(0).notNull(), // 0 or 1 (boolean)
  createdAt: timestamp("createdAt").defaultNow().notNull(),
  updatedAt: timestamp("updatedAt").defaultNow().onUpdateNow().notNull(),
});

export type FinancialProfile = typeof financialProfiles.$inferSelect;
export type InsertFinancialProfile = typeof financialProfiles.$inferInsert;

