// Relations
export const usersRelations = relations(users, ({ many }) => ({
  financialProfiles: many(financialProfiles),
  budgetAllocations: many(budgetAllocations),
  financialPlans: many(financialPlans),
  investmentGoals: many(investmentGoals),
  chatConversations: many(chatConversations),
}));

export const financialProfilesRelations = relations(financialProfiles, ({ one, many }) => ({
  user: one(users, {
    fields: [financialProfiles.userId],
    references: [users.id],
  }),
  budgetAllocations: many(budgetAllocations),
  financialPlans: many(financialPlans),
}));

export const budgetAllocationsRelations = relations(budgetAllocations, ({ one }) => ({
  user: one(users, {
    fields: [budgetAllocations.userId],
    references: [users.id],
  }),
  financialProfile: one(financialProfiles, {
    fields: [budgetAllocations.financialProfileId],
    references: [financialProfiles.id],
  }),
}));

export const financialPlansRelations = relations(financialPlans, ({ one }) => ({
  user: one(users, {
    fields: [financialPlans.userId],
    references: [users.id],
  }),
  financialProfile: one(financialProfiles, {
    fields: [financialPlans.financialProfileId],
    references: [financialProfiles.id],
  }),
}));

export const investmentGoalsRelations = relations(investmentGoals, ({ one }) => ({
  user: one(users, {
    fields: [investmentGoals.userId],
    references: [users.id],
  }),
}));

export const chatConversationsRelations = relations(chatConversations, ({ one }) => ({
  user: one(users, {
    fields: [chatConversations.userId],
    references: [users.id],
  }),
}));

